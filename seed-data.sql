    INSERT INTO tags (name) VALUES ('冒险') ON CONFLICT (name) DO NOTHING;
    INSERT INTO tags (name) VALUES ('史诗') ON CONFLICT (name) DO NOTHING;

    -- 为所有章节添加标签（使用 tag_id 而非 tag_name）
    INSERT INTO post_tags (post_id, tag_id)
    SELECT p.id, tags.id
    FROM posts p
    CROSS JOIN (VALUES ('奇幻'), ('长篇连载'), ('星辰之力'), ('原创'), ('冒险'), ('史诗')) AS t(name)
    JOIN tags ON tags.name = t.name
    WHERE p.series_name = series_name_val;
  END IF;
END $$;

